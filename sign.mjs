/**
 * Ed25519 签名封套（RFC 8032 PureEdDSA）。
 *
 * 签名域 = JCS(submission body) 的 UTF-8 字节，body 指作者提交的字段：
 *   author, title, summary, entries, tags, lineage, consent
 * 服务器附加字段（id/submittedAt/contentHash/hashAlg）不参与签名，
 * 这样验证方无需信任服务器的加字段行为。
 *
 * 封套（顶层 .sig）：
 *   { alg: "ed25519", keyId, publicKey: base64url(32B), value: base64url(64B) }
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalBytes } from './jcs.mjs';
import { keyIdOf, rawPublicKey, generateKeypair, savePrivateKey, registerKey, loadPrivateKey } from './keys.mjs';
import { prepareBody } from './body.mjs';

export const BODY_FIELDS = ['author', 'title', 'summary', 'entries', 'tags', 'lineage', 'consent'];

export function signingBody(record) {
  const out = {};
  for (const k of BODY_FIELDS) if (record[k] !== undefined) out[k] = record[k];
  return out;
}

/** 叶数据：签名后的完整提交内容（不含服务器附加字段）。 */
export function leafDataBytes(record) {
  const payload = { ...signingBody(record) };
  if (record.sig) payload.sig = record.sig;
  return canonicalBytes(payload);
}

/** 用私钥对 record 的 body 签名，返回封套（含公钥，便于自行验证）。 */
export function signRecord(record, privateKey, publicKey) {
  const raw = rawPublicKey(publicKey);
  const keyId = keyIdOf(raw);
  const value = crypto.sign(null, canonicalBytes(signingBody(record)), privateKey);
  return {
    alg: 'ed25519',
    keyId,
    publicKey: raw.toString('base64url'),
    value: value.toString('base64url'),
  };
}

/**
 * 验证封套。返回 { ok, keyId, reason }，不抛异常。
 * 校验项：算法、长度、keyId 与公钥一致、签名可验证。
 */
export function verifyRecordSignature(record, { requireKey = false } = {}) {
  const sig = record.sig;
  if (!sig) return { ok: !requireKey, keyId: null, reason: requireKey ? 'signature required' : 'unsigned' };
  if (sig.alg !== 'ed25519') return { ok: false, keyId: sig.keyId || null, reason: `unsupported alg: ${sig.alg}` };
  let rawPub;
  let sigBytes;
  try {
    rawPub = Buffer.from(sig.publicKey, 'base64url');
    sigBytes = Buffer.from(sig.value, 'base64url');
  } catch {
    return { ok: false, keyId: sig.keyId || null, reason: 'invalid base64url' };
  }
  if (rawPub.length !== 32) return { ok: false, keyId: sig.keyId || null, reason: 'publicKey must be 32 bytes' };
  if (sigBytes.length !== 64) return { ok: false, keyId: sig.keyId || null, reason: 'signature must be 64 bytes' };
  const derivedKeyId = keyIdOf(rawPub);
  if (sig.keyId && sig.keyId !== derivedKeyId) return { ok: false, keyId: sig.keyId, reason: 'keyId does not match publicKey' };
  try {
    // 从原始 32 字节公钥重建 SPKI：Ed25519 SubjectPublicKeyInfo 前缀固定
    const spki = Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), rawPub]);
    const key = crypto.createPublicKey({ key: spki, format: 'der', type: 'spki' });
    const ok = crypto.verify(null, canonicalBytes(signingBody(record)), key, sigBytes);
    return { ok, keyId: derivedKeyId, reason: ok ? 'ok' : 'signature mismatch' };
  } catch (e) {
    return { ok: false, keyId: derivedKeyId, reason: `malformed public key: ${e.message}` };
  }
}

// ---------- CLI ----------
const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const cmd = process.argv[2];
  const flag = (n) => { const i = process.argv.indexOf(`--${n}`); return i > -1 ? process.argv[i + 1] : null; };
  try {
    if (cmd === 'keygen') {
      const author = flag('author');
      if (!author) { console.error('usage: sign.mjs keygen --author <name>'); process.exit(2); }
      const kp = generateKeypair();
      savePrivateKey(kp.keyId, kp.privateKeyPem);
      registerKey({ keyId: kp.keyId, publicKeyPem: kp.publicKeyPem, author, note: 'generated by CLI' });
      console.log(JSON.stringify({ keyId: kp.keyId, author, privateKey: `<DREAM_HOME>/keys/${kp.keyId}.private.pem` }, null, 2));
    } else if (cmd === 'sign') {
      const file = flag('file');
      const keyId = flag('key');
      if (!file || !keyId) { console.error('usage: sign.mjs sign --file <json> --key <keyId> [--out file]'); process.exit(2); }
      const privateKey = loadPrivateKey(keyId);
      const { body } = prepareBody(JSON.parse(fs.readFileSync(file, 'utf8')));
      // Ed25519 私钥可推导公钥，无需单独读取
      const derivedPub = crypto.createPublicKey(privateKey);
      const sig = signRecord(body, privateKey, derivedPub);
      const out = JSON.stringify({ ...body, sig }, null, 2);
      const outFile = flag('out');
      if (outFile) fs.writeFileSync(outFile, out + '\n', 'utf8');
      console.log(out);
    } else if (cmd === 'verify') {
      const file = flag('file');
      if (!file) { console.error('usage: sign.mjs verify --file <json>'); process.exit(2); }
      const record = JSON.parse(fs.readFileSync(file, 'utf8'));
      const result = verifyRecordSignature(record, { requireKey: true });
      console.log(JSON.stringify(result, null, 2));
      process.exit(result.ok ? 0 : 1);
    } else {
      console.log(`dream-mcp 签名工具
  keygen --author <name>                     生成密钥并登记作者（TOFU）
  sign   --file <raw.json> --key <keyId>     规范化 + 签名，输出可提交的 JSON
  verify --file <signed.json>                验证签名`);
    }
  } catch (e) {
    console.error('error:', e.message);
    process.exit(1);
  }
}
